# Create a dictionary
my_dict = {
    "brand": "Ford",
    "model": "Mustang",
    "year": 1964
}

# Display all keys
print("All Keys:", list(my_dict.keys()))

# Display all values
print("All Values:", list(my_dict.values()))

# Display all key-value pairs
print("All Key-Value Pairs:", list(my_dict.items()))
