# Student subjects stored in two sets
student1_subjects = {"Math", "Physics", "Chemistry"}
student2_subjects = {"Chemistry", "Biology", "Math"}

# Determine the subjects studied by both students
common_subjects = student1_subjects.intersection(student2_subjects)

# Display the results
print("Student 1 subjects:", student1_subjects)
print("Student 2 subjects:", student2_subjects)
print("Subjects studied by both students:", common_subjects)
